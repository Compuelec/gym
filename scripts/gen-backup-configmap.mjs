// Generates deploy/k8s/backup-scripts.yaml from deploy/backup/*.sh (same approach as Al Día).
import { readFileSync, writeFileSync } from 'node:fs';

const files = ['backup.sh', 'verify.sh'];
const indent = (s) => s.split('\n').map((l) => (l ? `    ${l}` : '')).join('\n');
const body = files.map((f) => `  ${f}: |\n${indent(readFileSync(`deploy/backup/${f}`, 'utf8').trimEnd())}`).join('\n');
const yaml = `# Generated by scripts/gen-backup-configmap.mjs from deploy/backup/*.sh. Do not edit by hand.
apiVersion: v1
kind: ConfigMap
metadata:
  name: gym-backup-scripts
  namespace: gym
data:
${body}
`;
if (process.argv.includes('--check')) {
  const current = readFileSync('deploy/k8s/backup-scripts.yaml', 'utf8');
  if (current !== yaml) {
    console.error('deploy/k8s/backup-scripts.yaml is out of date: run node scripts/gen-backup-configmap.mjs');
    process.exit(1);
  }
} else {
  writeFileSync('deploy/k8s/backup-scripts.yaml', yaml);
}
